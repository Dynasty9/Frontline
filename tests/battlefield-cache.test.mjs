import { test } from "node:test";
import assert from "node:assert/strict";
import { runFixture } from "./lib/fixture.mjs";
import { ROOT } from "./lib/game.mjs";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

test("battlefield packages validate inputs, code, integrity and atomic repair", async () => {
  assert.match(await runFixture("battlefield-cache"), /BATTLEFIELD_CACHE_TEST passed/);
});

test("precomputed starts preserve generated bytes and independently verified replays", { timeout: 240_000 }, async (t) => {
  const folder = await mkdtemp(path.join(tmpdir(), "frontline-map-test-"));
  t.after(() => rm(folder, { recursive: true, force: true }));
  const config = path.join(folder, "config.json");
  await writeFile(config, JSON.stringify({ fixed_seed: 3, map_size: 1024,
    scenario: "stress", stress_units: 4, stress_scenery: 0, stress_vehicles: 0,
    stress_mode: "combat", ai_fill: false, team: -1, name: "Cache fixture" }));
  await promisify(execFile)(process.env.PYTHON || "python", ["tools/bake_maps.py",
    "--config", config, "--output", folder, "--benchmark", "--ticks", "60",
    "--godot", process.env.GODOT || "godot"], { cwd: ROOT, timeout: 230_000 });
  const { runs } = JSON.parse(await readFile(path.join(folder, "results.json"), "utf8"));
  assert.deepEqual(runs.map(run => run.cache_hit), [false, false, true, true]);
  assert.equal(new Set(runs.map(run => run.initial_sha256)).size, 1);
  assert.equal(new Set(runs.map(run => run.verification)).size, 1);
});
